-- LeadOrbit subscriptions (plans, subscriptions, billing periods, job runs) and
-- manually verified payments (payments, proofs, events).

-- ------------------------------------------------------------------ plans

CREATE TABLE plans (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(40)  NOT NULL,
    name              VARCHAR(120) NOT NULL,
    service_id        BIGINT REFERENCES services (id) ON DELETE SET NULL,
    amount            NUMERIC(14,2) NOT NULL,
    billing_interval  VARCHAR(20) NOT NULL,
    tax_inclusive     BOOLEAN     NOT NULL DEFAULT FALSE,
    description       VARCHAR(500),
    active            BOOLEAN     NOT NULL DEFAULT TRUE,
    version           BIGINT      NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ,
    deleted_at        TIMESTAMPTZ,
    CONSTRAINT uq_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_amount CHECK (amount > 0),
    CONSTRAINT ck_plans_interval CHECK (billing_interval IN ('MONTHLY', 'QUARTERLY', 'YEARLY'))
);

-- ------------------------------------------------------------------ subscriptions

CREATE TABLE subscriptions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id            BIGINT      NOT NULL REFERENCES plans (id) ON DELETE RESTRICT,
    company_id         BIGINT      REFERENCES companies (id) ON DELETE RESTRICT,
    contact_id         BIGINT      REFERENCES contacts (id) ON DELETE RESTRICT,
    status             VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    start_date         DATE        NOT NULL,
    end_date           DATE,
    anchor_day         INTEGER     NOT NULL DEFAULT 1,
    zone_id            VARCHAR(64) NOT NULL DEFAULT 'UTC',
    next_billing_date  DATE,
    price_override     NUMERIC(14,2),
    version            BIGINT      NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    deleted_at         TIMESTAMPTZ,
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'PAUSED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_subscriptions_anchor CHECK (anchor_day BETWEEN 1 AND 31),
    CONSTRAINT ck_subscriptions_customer CHECK (company_id IS NOT NULL OR contact_id IS NOT NULL),
    CONSTRAINT ck_subscriptions_price CHECK (price_override IS NULL OR price_override > 0)
);
CREATE INDEX idx_subscriptions_plan ON subscriptions (plan_id);
CREATE INDEX idx_subscriptions_company ON subscriptions (company_id);
CREATE INDEX idx_subscriptions_contact ON subscriptions (contact_id);
CREATE INDEX idx_subscriptions_status ON subscriptions (status, next_billing_date);

-- ------------------------------------------------------------------ billing periods + job runs

CREATE TABLE subscription_billing_periods (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT      NOT NULL REFERENCES subscriptions (id) ON DELETE CASCADE,
    period_start    DATE        NOT NULL,
    period_end      DATE        NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    invoice_id      BIGINT      REFERENCES invoices (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT uq_period UNIQUE (subscription_id, period_start),
    CONSTRAINT ck_period_amount CHECK (amount > 0),
    CONSTRAINT ck_period_status CHECK (status IN ('PENDING', 'INVOICED', 'PAID', 'SKIPPED')),
    CONSTRAINT ck_period_range CHECK (period_end >= period_start)
);
CREATE INDEX idx_periods_subscription ON subscription_billing_periods (subscription_id, period_start);
CREATE INDEX idx_periods_invoice ON subscription_billing_periods (invoice_id) WHERE invoice_id IS NOT NULL;

CREATE TABLE billing_job_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name      VARCHAR(60) NOT NULL,
    scheduled_for DATE        NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ,
    total_items   INTEGER     NOT NULL DEFAULT 0,
    success_count INTEGER     NOT NULL DEFAULT 0,
    skipped_count INTEGER     NOT NULL DEFAULT 0,
    failed_count  INTEGER     NOT NULL DEFAULT 0,
    error         VARCHAR(2000),
    CONSTRAINT uq_job_run UNIQUE (job_name, scheduled_for),
    CONSTRAINT ck_job_run_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE billing_job_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT      NOT NULL REFERENCES billing_job_runs (id) ON DELETE CASCADE,
    subscription_id BIGINT      NOT NULL REFERENCES subscriptions (id) ON DELETE CASCADE,
    period_start    DATE        NOT NULL,
    outcome         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    message         VARCHAR(1000),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_job_item UNIQUE (subscription_id, period_start),
    CONSTRAINT ck_job_item_outcome CHECK (outcome IN ('PENDING', 'SUCCESS', 'SKIPPED', 'FAILED'))
);
CREATE INDEX idx_job_items_run ON billing_job_items (run_id);

-- ------------------------------------------------------------------ payments

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      BIGINT      NOT NULL REFERENCES invoices (id) ON DELETE RESTRICT,
    amount          NUMERIC(14,2) NOT NULL,
    method          VARCHAR(20) NOT NULL,
    reference_no    VARCHAR(80),
    paid_on         DATE        NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
    notes           VARCHAR(1000),
    submitted_by    BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    verified_by     BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    verified_at     TIMESTAMPTZ,
    rejection_reason VARCHAR(500),
    idempotency_key VARCHAR(120),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'VERIFIED', 'REJECTED', 'NEEDS_INFO')),
    CONSTRAINT ck_payment_method CHECK (method IN ('UPI', 'NEFT', 'RTGS', 'IMPS', 'CHEQUE', 'CASH', 'OTHER'))
);
CREATE UNIQUE INDEX uq_payment_ref ON payments (invoice_id, reference_no) WHERE reference_no IS NOT NULL;
CREATE UNIQUE INDEX uq_payment_idem ON payments (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX idx_payments_invoice ON payments (invoice_id, status);
CREATE INDEX idx_payments_status ON payments (status);

CREATE TABLE payment_proofs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id        BIGINT      NOT NULL REFERENCES payments (id) ON DELETE CASCADE,
    storage_key       VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type      VARCHAR(120),
    size_bytes        BIGINT      NOT NULL,
    sha256            VARCHAR(64) NOT NULL,
    uploaded_by       BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    uploaded_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payment_proofs_payment ON payment_proofs (payment_id);

CREATE TABLE payment_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id    BIGINT NOT NULL REFERENCES payments (id) ON DELETE CASCADE,
    event_type    VARCHAR(40) NOT NULL,
    actor_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    description   VARCHAR(1000),
    data          JSONB
);
CREATE INDEX idx_payment_events_payment ON payment_events (payment_id, occurred_at);