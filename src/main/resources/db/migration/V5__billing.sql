-- LeadOrbit billing: seller profiles, invoice numbering, GST invoices, line items, events.

CREATE TABLE seller_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_name          VARCHAR(180) NOT NULL,
    trade_name          VARCHAR(180),
    gstin               VARCHAR(20)  NOT NULL,
    state_code          VARCHAR(4)   NOT NULL,
    registered_address  VARCHAR(500) NOT NULL,
    logo_path           VARCHAR(255),
    is_default          BOOLEAN      NOT NULL DEFAULT FALSE,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ,
    deleted_at          TIMESTAMPTZ,
    CONSTRAINT uq_seller_profiles_gstin UNIQUE (gstin)
);
CREATE UNIQUE INDEX uq_seller_profiles_default ON seller_profiles (is_default) WHERE is_default = TRUE;

CREATE TABLE invoice_number_sequences (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id      BIGINT      NOT NULL REFERENCES seller_profiles (id) ON DELETE CASCADE,
    doc_type       VARCHAR(20) NOT NULL,
    financial_year VARCHAR(9)  NOT NULL,
    prefix         VARCHAR(20) NOT NULL,
    next_number    BIGINT      NOT NULL DEFAULT 1,
    padding        INTEGER     NOT NULL DEFAULT 6,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ,
    CONSTRAINT uq_invoice_sequence UNIQUE (seller_id, doc_type, financial_year),
    CONSTRAINT ck_invoice_sequence_padding CHECK (padding BETWEEN 1 AND 12)
);

CREATE TABLE invoices (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number        VARCHAR(40),
    doc_type              VARCHAR(20) NOT NULL DEFAULT 'TAX_INVOICE',
    seller_id             BIGINT NOT NULL REFERENCES seller_profiles (id) ON DELETE RESTRICT,
    company_id            BIGINT REFERENCES companies (id) ON DELETE RESTRICT,
    contact_id            BIGINT REFERENCES contacts (id) ON DELETE RESTRICT,
    lead_id               BIGINT REFERENCES leads (id) ON DELETE RESTRICT,
    status                VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    invoice_date          DATE,
    issue_date            DATE,
    due_date              DATE,
    place_of_supply_state VARCHAR(4),
    currency              VARCHAR(3) NOT NULL DEFAULT 'INR',
    tax_inclusive         BOOLEAN    NOT NULL DEFAULT FALSE,
    taxable_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    cgst_amount           NUMERIC(14,2) NOT NULL DEFAULT 0,
    sgst_amount           NUMERIC(14,2) NOT NULL DEFAULT 0,
    igst_amount           NUMERIC(14,2) NOT NULL DEFAULT 0,
    cess_amount           NUMERIC(14,2) NOT NULL DEFAULT 0,
    round_off             NUMERIC(5,2)  NOT NULL DEFAULT 0,
    grand_total           NUMERIC(14,2) NOT NULL DEFAULT 0,
    amount_paid           NUMERIC(14,2) NOT NULL DEFAULT 0,
    seller_snapshot       JSONB,
    customer_snapshot     JSONB,
    lines_snapshot        JSONB,
    issued_at             TIMESTAMPTZ,
    cancelled_at          TIMESTAMPTZ,
    cancel_reason         VARCHAR(500),
    created_by            BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ,
    version               BIGINT NOT NULL DEFAULT 0,
    deleted_at            TIMESTAMPTZ,
    CONSTRAINT ck_invoices_doc_type CHECK (doc_type IN ('TAX_INVOICE', 'CREDIT_NOTE', 'DEBIT_NOTE', 'BILL_OF_SUPPLY', 'PROFORMA')),
    CONSTRAINT ck_invoices_status CHECK (status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'OVERDUE', 'CANCELLED')),
    CONSTRAINT ck_invoices_reference CHECK (lead_id IS NOT NULL OR contact_id IS NOT NULL OR company_id IS NOT NULL),
    CONSTRAINT ck_invoices_amounts CHECK (
        taxable_amount >= 0 AND cgst_amount >= 0 AND sgst_amount >= 0 AND
        igst_amount >= 0 AND cess_amount >= 0 AND grand_total >= 0 AND amount_paid >= 0),
    CONSTRAINT ck_invoices_number_status CHECK (
        (invoice_number IS NULL AND status = 'DRAFT') OR (invoice_number IS NOT NULL AND status <> 'DRAFT'))
);
CREATE UNIQUE INDEX uq_invoices_number ON invoices (invoice_number) WHERE invoice_number IS NOT NULL;
CREATE INDEX idx_invoices_lead ON invoices (lead_id);
CREATE INDEX idx_invoices_company ON invoices (company_id);
CREATE INDEX idx_invoices_status ON invoices (status);
CREATE INDEX idx_invoices_due_date ON invoices (due_date) WHERE status IN ('ISSUED', 'PARTIALLY_PAID', 'OVERDUE');

CREATE TABLE invoice_line_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id        BIGINT NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    service_id        BIGINT REFERENCES services (id) ON DELETE SET NULL,
    description       VARCHAR(500) NOT NULL,
    hsn_sac           VARCHAR(16)  NOT NULL,
    quantity          NUMERIC(14,4) NOT NULL DEFAULT 1,
    unit              VARCHAR(20),
    rate              NUMERIC(14,2) NOT NULL,
    discount          NUMERIC(14,2) NOT NULL DEFAULT 0,
    taxable_value     NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax_class         VARCHAR(20)  NOT NULL,
    gst_rate          NUMERIC(5,2) NOT NULL DEFAULT 0,
    cgst_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    sgst_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    igst_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    cess_amount       NUMERIC(14,2) NOT NULL DEFAULT 0,
    line_total        NUMERIC(14,2) NOT NULL DEFAULT 0,
    service_snapshot  JSONB,
    sort_order        INTEGER NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_line_items_amounts CHECK (
        quantity >= 0 AND rate >= 0 AND discount >= 0 AND taxable_value >= 0 AND line_total >= 0)
);
CREATE INDEX idx_invoice_line_items_invoice ON invoice_line_items (invoice_id);

CREATE TABLE invoice_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    BIGINT NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    event_type    VARCHAR(40) NOT NULL,
    actor_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    description   VARCHAR(1000),
    data          JSONB
);
CREATE INDEX idx_invoice_events_invoice ON invoice_events (invoice_id, occurred_at);