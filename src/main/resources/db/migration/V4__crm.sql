-- LeadOrbit CRM: companies, contacts, lead sources, pipeline stages, leads, activities, consents.

CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(180) NOT NULL,
    legal_name  VARCHAR(180),
    gstin       VARCHAR(20),
    state_code  VARCHAR(4),
    address     VARCHAR(500),
    city        VARCHAR(100),
    state       VARCHAR(100),
    country     VARCHAR(60)  NOT NULL DEFAULT 'IN',
    pincode     VARCHAR(12),
    phone       VARCHAR(30),
    website     VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    deleted_at  TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_companies_name ON companies (name) WHERE deleted_at IS NULL;
CREATE INDEX idx_companies_name ON companies (name);

CREATE TABLE contacts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         BIGINT REFERENCES companies (id) ON DELETE SET NULL,
    name               VARCHAR(150) NOT NULL,
    email              VARCHAR(255),
    phone              VARCHAR(30),
    designation        VARCHAR(120),
    marketing_opt_in   BOOLEAN      NOT NULL DEFAULT FALSE,
    consent_at         TIMESTAMPTZ,
    unsubscribed_at    TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ,
    deleted_at         TIMESTAMPTZ
);
CREATE INDEX idx_contacts_company ON contacts (company_id);
CREATE UNIQUE INDEX uq_contacts_email ON contacts (email) WHERE email IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE lead_sources (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30) NOT NULL,
    name       VARCHAR(80) NOT NULL,
    channel    VARCHAR(20) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_lead_sources_code UNIQUE (code),
    CONSTRAINT ck_lead_sources_channel CHECK (channel IN ('WEBSITE', 'CAMPAIGN', 'REFERRAL', 'SOCIAL', 'EVENT', 'OTHER'))
);

CREATE TABLE pipeline_stages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(40) NOT NULL,
    name       VARCHAR(80) NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    is_won     BOOLEAN     NOT NULL DEFAULT FALSE,
    is_lost     BOOLEAN     NOT NULL DEFAULT FALSE,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pipeline_stages_code UNIQUE (code),
    CONSTRAINT ck_pipeline_stage_exclusive CHECK (NOT (is_won AND is_lost))
);

CREATE TABLE leads (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(200) NOT NULL,
    company_id            BIGINT REFERENCES companies (id) ON DELETE SET NULL,
    contact_id            BIGINT REFERENCES contacts (id) ON DELETE SET NULL,
    source_id             BIGINT REFERENCES lead_sources (id) ON DELETE SET NULL,
    stage_id              BIGINT NOT NULL REFERENCES pipeline_stages (id) ON DELETE RESTRICT,
    owner_id              BIGINT REFERENCES users (id) ON DELETE SET NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    value                 NUMERIC(14,2) NOT NULL DEFAULT 0,
    advance_amount        NUMERIC(14,2) NOT NULL DEFAULT 0,
    notes                 TEXT,
    converted_at          TIMESTAMPTZ,
    converted_contact_id  BIGINT REFERENCES contacts (id) ON DELETE SET NULL,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ,
    deleted_at            TIMESTAMPTZ,
    CONSTRAINT ck_leads_status CHECK (status IN ('OPEN', 'WON', 'LOST')),
    CONSTRAINT ck_leads_value CHECK (value >= 0),
    CONSTRAINT ck_leads_advance CHECK (advance_amount >= 0),
    CONSTRAINT ck_leads_reference CHECK (company_id IS NOT NULL OR contact_id IS NOT NULL)
);
CREATE UNIQUE INDEX uq_leads_converted_contact ON leads (converted_contact_id)
    WHERE converted_contact_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX idx_leads_stage ON leads (stage_id);
CREATE INDEX idx_leads_owner ON leads (owner_id);
CREATE INDEX idx_leads_company ON leads (company_id);
CREATE INDEX idx_leads_contact ON leads (contact_id);
CREATE INDEX idx_leads_status ON leads (status);

CREATE TABLE activities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id     BIGINT NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
    type        VARCHAR(30) NOT NULL,
    subject     VARCHAR(200) NOT NULL,
    body        TEXT,
    due_at      TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    assignee_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    CONSTRAINT ck_activities_type CHECK (type IN ('CALL', 'EMAIL', 'MEETING', 'NOTE', 'TASK'))
);
CREATE INDEX idx_activities_lead ON activities (lead_id, created_at);

CREATE TABLE consents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT NOT NULL REFERENCES contacts (id) ON DELETE CASCADE,
    channel     VARCHAR(20) NOT NULL,
    purpose     VARCHAR(80) NOT NULL,
    granted     BOOLEAN     NOT NULL,
    granted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at  TIMESTAMPTZ,
    source      VARCHAR(40),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_consents_channel CHECK (channel IN ('EMAIL', 'SMS', 'PHONE'))
);

