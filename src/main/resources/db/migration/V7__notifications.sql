-- LeadOrbit notifications: templates, transactional outbox and delivery log.

CREATE TABLE email_templates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(60)  NOT NULL,
    subject       VARCHAR(200) NOT NULL,
    body_template TEXT         NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    CONSTRAINT uq_email_templates_code UNIQUE (code)
);

CREATE TABLE notification_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(120) NOT NULL,
    event_type      VARCHAR(40)  NOT NULL,
    template_id     BIGINT       NOT NULL REFERENCES email_templates (id) ON DELETE RESTRICT,
    recipient_email VARCHAR(255) NOT NULL,
    subject         VARCHAR(200) NOT NULL,
    body            TEXT         NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    attempts        INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ,
    sent_at         TIMESTAMPTZ,
    last_error      VARCHAR(1000),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ,
    CONSTRAINT uq_outbox_idem UNIQUE (idempotency_key),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED'))
);
CREATE INDEX idx_outbox_status ON notification_outbox (status, next_attempt_at);

CREATE TABLE email_delivery_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outbox_id   BIGINT       NOT NULL REFERENCES notification_outbox (id) ON DELETE CASCADE,
    provider    VARCHAR(20)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    message     VARCHAR(500),
    occurred_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_delivery_outbox ON email_delivery_log (outbox_id);

