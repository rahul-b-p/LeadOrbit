-- LeadOrbit: service catalog and configurable GST rate table.
-- Rates are configuration placeholders; exact applicability must be confirmed by a
-- tax professional before production use.

CREATE TABLE services (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40)  NOT NULL,
    name             VARCHAR(150) NOT NULL,
    description      VARCHAR(500),
    hsn_sac          VARCHAR(16)  NOT NULL,
    tax_class        VARCHAR(20)  NOT NULL DEFAULT 'TAXABLE',
    default_gst_rate NUMERIC(5,2) NOT NULL DEFAULT 18.00,
    unit             VARCHAR(20),
    default_rate     NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax_inclusive    BOOLEAN      NOT NULL DEFAULT FALSE,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    CONSTRAINT uq_services_code UNIQUE (code),
    CONSTRAINT ck_services_tax_class CHECK (tax_class IN ('TAXABLE', 'EXEMPT', 'NIL_RATED', 'ZERO_RATED', 'NON_GST')),
    CONSTRAINT ck_services_rate       CHECK (default_rate >= 0),
    CONSTRAINT ck_services_tax_rate   CHECK (default_gst_rate >= 0 AND default_gst_rate <= 100)
);

CREATE INDEX idx_services_active ON services (active);

CREATE TABLE gst_rates (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)  NOT NULL,
    name           VARCHAR(80)  NOT NULL,
    rate           NUMERIC(5,2) NOT NULL,
    effective_from DATE         NOT NULL,
    effective_to   DATE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_gst_rates_code UNIQUE (code),
    CONSTRAINT ck_gst_rates_rate CHECK (rate >= 0)
);

