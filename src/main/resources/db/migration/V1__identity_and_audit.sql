-- LeadOrbit baseline: identity, authorization and append-only audit.
-- Portfolio-safe: no client data, no secrets.

-- ---------------------------------------------------------------------------
-- Identity
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash TEXT         NOT NULL,
    phone_number  VARCHAR(30),
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    deleted_at    TIMESTAMPTZ,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(60)  NOT NULL,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(255),
    rank        INTEGER      NOT NULL DEFAULT 0,
    system_role BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(80)  NOT NULL,
    module      VARCHAR(40)  NOT NULL,
    action      VARCHAR(40)  NOT NULL,
    description VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_permissions_code UNIQUE (code)
);

CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE user_roles (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id    BIGINT NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
    granted_by BIGINT REFERENCES users (id) ON DELETE SET NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);

-- Explicit per-user grants/revocations layered on top of role permissions.
CREATE TABLE user_permissions (
    user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    permission_id BIGINT      NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    effect        VARCHAR(10) NOT NULL,
    granted_by    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    granted_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, permission_id),
    CONSTRAINT ck_user_permissions_effect CHECK (effect IN ('GRANT', 'REVOKE'))
);

-- Persisted, rotating refresh tokens (stored only as a hash).
CREATE TABLE refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   VARCHAR(128) NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked_at   TIMESTAMPTZ,
    replaced_by  BIGINT REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    user_agent   VARCHAR(512),
    ip_address   VARCHAR(64),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------------
-- Audit (append-only; UPDATE/DELETE blocked by trigger)
-- ---------------------------------------------------------------------------
CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_uid      UUID         NOT NULL DEFAULT gen_random_uuid(),
    occurred_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actor_user_id  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_label    VARCHAR(150),
    action         VARCHAR(80)  NOT NULL,
    entity_type    VARCHAR(80),
    entity_id      VARCHAR(80),
    outcome        VARCHAR(20)  NOT NULL,
    correlation_id VARCHAR(64),
    request_id     VARCHAR(64),
    ip_address     VARCHAR(64),
    user_agent     VARCHAR(512),
    summary        VARCHAR(1000),
    before_data    JSONB,
    after_data     JSONB,
    CONSTRAINT uq_audit_event_uid UNIQUE (event_uid),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);
CREATE INDEX idx_audit_occurred_at ON audit_events (occurred_at);
CREATE INDEX idx_audit_actor ON audit_events (actor_user_id);
CREATE INDEX idx_audit_entity ON audit_events (entity_type, entity_id);

CREATE FUNCTION prevent_audit_mutation() RETURNS trigger AS $fn$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only and cannot be updated or deleted';
END;
$fn$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_no_update
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
